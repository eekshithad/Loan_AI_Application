def _cases_to_arrays():
    """Convert synthetic training data to numpy arrays."""
    X, y = [], []
    for case in SYNTHETIC_TRAINING_CASES:
        X.append(list(case[:8]))
        y.append(case[8])
    return np.array(X, dtype=float), np.array(y)


def build_feature_vector(
    credit_score: Optional[float],
    as_is_ltv: Optional[float],
    arv_ltv: Optional[float],
    ltc: Optional[float],
    bank_balance: Optional[float],
    loan_amount: Optional[float],
    doc_completeness_pct: float,
    experience_years: Optional[float],
    missing_required_docs: int,
) -> np.ndarray:
    """
    Convert extracted underwriting data into the ML feature vector.
    Missing values are imputed with conservative (risk-indicating) defaults.
    """
    # Impute missing values with conservative defaults
    cs = credit_score if credit_score is not None else 620.0
    ltv = as_is_ltv if as_is_ltv is not None else 80.0
    arv_l = arv_ltv if arv_ltv is not None else 75.0
    l_tc = ltc if ltc is not None else 85.0

    # Bank balance ratio (balance / loan_amount)
    if bank_balance is not None and loan_amount and loan_amount > 0:
        balance_ratio = bank_balance / loan_amount
    else:
        balance_ratio = 0.05  # Conservative default

    completeness = doc_completeness_pct
    exp = experience_years if experience_years is not None else 0.0
    missing = float(missing_required_docs)

    return np.array([[cs, ltv, arv_l, l_tc, balance_ratio, completeness, exp, missing]])


class LoanDecisionModel:
    """Random Forest classifier for loan decisions."""

    def __init__(self):
        self.model: Optional[RandomForestClassifier] = None
        self.label_encoder = LabelEncoder()
        self.feature_names = [
            "credit_score",
            "as_is_ltv",
            "arv_ltv",
            "ltc",
            "bank_balance_ratio",
            "doc_completeness_pct",
            "experience_years",
            "missing_required_docs",
        ]
        self.is_trained = False
        self.training_report = {}

    def train(self):
        """Train the model on synthetic data."""
        X, y_raw = _cases_to_arrays()
        y = self.label_encoder.fit_transform(y_raw)

        # Train/test split for evaluation
        X_train, X_test, y_train, y_test = train_test_split(
            X, y, test_size=0.25, random_state=42, stratify=y
        )

        self.model = RandomForestClassifier(
            n_estimators=100,
            max_depth=6,
            random_state=42,
            class_weight="balanced",
        )
        self.model.fit(X_train, y_train)
        self.is_trained = True

        # Evaluate on held-out set
        y_pred = self.model.predict(X_test)
        labels = self.label_encoder.classes_
        self.training_report = {
            "classification_report": classification_report(
                y_test, y_pred,
                target_names=labels,
                output_dict=True,
            ),
            "confusion_matrix": confusion_matrix(y_test, y_pred).tolist(),
            "label_order": labels.tolist(),
            "train_size": len(X_train),
            "test_size": len(X_test),
            "model_info": "Multi-variable Random Forest classifier trained on 8 key underwriting factors with balanced class weighting.",
        }
        logger.info(f"Model trained. Test set accuracy: "
                    f"{self.training_report['classification_report']['accuracy']:.2%}")

        # Save model
        self._save()
        return self.training_report

    def _save(self):
        MODEL_PATH.parent.mkdir(exist_ok=True)
        with open(MODEL_PATH, "wb") as f:
            pickle.dump((self.model, self.label_encoder), f)

    def load_or_train(self):
        """Load existing model or train a new one."""
        if MODEL_PATH.exists():
            try:
                with open(MODEL_PATH, "rb") as f:
                    self.model, self.label_encoder = pickle.load(f)
                self.is_trained = True
                logger.info("Loaded existing loan decision model from disk.")
                return
            except Exception as exc:
                logger.warning(f"Could not load model: {exc}, retraining...")
        self.train()

    def predict(self, feature_vector: np.ndarray) -> dict:
        """
        Make a loan decision prediction.
        Returns dict with decision, probabilities, and feature importances.
        """
        if not self.is_trained:
            self.load_or_train()

        proba = self.model.predict_proba(feature_vector)[0]
        pred_idx = np.argmax(proba)
        pred_label = self.label_encoder.inverse_transform([pred_idx])[0]

        # Map probabilities to class names
        classes = self.label_encoder.classes_
        prob_dict = {cls: round(float(p), 3) for cls, p in zip(classes, proba)}

        # Feature importances
        importances = self.model.feature_importances_
        fi = sorted(
            zip(self.feature_names, importances),
            key=lambda x: x[1], reverse=True
        )
        top_features = [
            {"feature": name, "importance": round(float(imp), 3)}
            for name, imp in fi[:5]
        ]

        return {
            "decision": pred_label,
            "probabilities": prob_dict,
            "top_features": top_features,
            "confidence": round(float(proba[pred_idx]), 3),
        }


def generate_decision_explanation(
    prediction: dict,
    extraction_result,
    financial_metrics,
    validation_result,
    ollama_client,
) -> str:
    """
    Use LLM to generate a human-readable explanation of the loan decision.
    The LLM explains; it does NOT make the decision (that was the ML model).
    """
    ext = extraction_result
    fm = financial_metrics
    val = validation_result

    as_is_str = f"{fm.as_is_ltv:.1f}%" if fm.as_is_ltv is not None else "N/A"
    arv_str = f"{fm.arv_ltv:.1f}%" if fm.arv_ltv is not None else "N/A"
    ltc_str = f"{fm.ltc:.1f}%" if fm.ltc is not None else "N/A"
    equity_str = f"${fm.borrower_equity:,.0f}" if fm.borrower_equity is not None else "N/A"

    context = f"""
Loan Decision: {prediction['decision']}
Decision Confidence: {prediction['confidence']:.1%}

Key Financial Metrics:
- Credit Score: {ext.borrower.credit_score.value}
- As-Is LTV: {as_is_str}
- ARV LTV: {arv_str}
- LTC: {ltc_str}
- Borrower Equity: {equity_str}
- Bank Balance: {ext.borrower.bank_balance.value}
- Experience: {ext.borrower.experience_years.value} years

Document Issues:
- Missing Required Docs: {len(val.missing_required)}
- Total Issues Found: {len(val.issues)}

Top ML Model Factors: {', '.join(f["feature"] for f in prediction.get("top_features", [])[:3])}
"""

    prompt = f"""You are a senior loan underwriter explaining a loan decision to a junior colleague.

Based on this loan analysis:
{context}

Write a clear, professional 3-4 paragraph explanation of the {prediction['decision']} decision.
Include:
1. The primary reason for this decision
2. Key strengths of this loan request (if any)
3. Key concerns or risks
4. What conditions or actions are needed (if CONDITIONAL_APPROVAL or DECLINE)

Write in plain English. Be specific and reference the actual numbers above.
Do not use bullet points. Write in paragraphs.
"""

    try:
        return ollama_client.chat(prompt)
    except Exception as exc:
        logger.warning(f"LLM explanation failed: {exc}")
        return _fallback_explanation(prediction, fm, val)


def _fallback_explanation(prediction: dict, fm, val) -> str:
    """Generate a rule-based explanation when LLM is unavailable."""
    decision = prediction["decision"]
    issues = [i.description for i in val.issues[:3]]
    flags = fm.flags[:3] if fm.flags else []

    if decision == "APPROVE":
        return (
            "The loan application meets the required underwriting criteria. "
            "The borrower demonstrates adequate credit quality, sufficient equity, "
            "and acceptable loan-to-value ratios. "
            "The documentation package is reasonably complete."
        )
    elif decision == "CONDITIONAL_APPROVAL":
        conditions = "; ".join(issues[:2]) if issues else "minor documentation gaps"
        return (
            f"The loan application is conditionally approved pending resolution of: {conditions}. "
            f"The underlying collateral and borrower profile are acceptable, but certain "
            f"conditions must be satisfied before funding can proceed."
        )
    else:
        reasons = "; ".join(issues[:2] + flags[:1]) if (issues or flags) else "loan metrics do not meet requirements"
        return (
            f"The loan application is declined due to: {reasons}. "
            f"The application does not meet the minimum underwriting standards "
            f"required for approval at this time."
        )

